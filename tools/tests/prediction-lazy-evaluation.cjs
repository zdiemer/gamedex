const { readAppSource } = require('./app-source.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = {};
vm.createContext(context);
vm.runInContext(readAppSource('static/predict.js', 'utf8'), context);
vm.runInContext(`
let fits = 0, evaluations = 0;
const DATA = {sheets: {completed: {rows: Array.from({length: 100}, () => ({rating: 0.8}))}}};
fitEncoder = () => { fits++; return {global: 0.8, baselineNow: 0.8, critic: {}, players: {}}; };
fitWeights = () => () => 0.75;
evaluateScope = () => { evaluations++; return {mae: 0.1}; };
`, context);
const run = code => vm.runInContext(code, context);
assert.equal(run('tasteModel().predict([])'), 0.75);
assert.equal(run('fits'), 1);
assert.equal(run('evaluations'), 0, 'predicting does not cross-validate');
assert.equal(run('tasteModel().eval.mae'), 0.1);
assert.equal(run('tasteModel().eval.mae'), 0.1);
assert.equal(run('evaluations'), 1, 'accuracy is computed only once');
assert.equal(run('tasteModel().igdb.predict([])'), 0.75);
assert.equal(run('fits'), 2);
assert.equal(run('evaluations'), 1, 'restricted predictions also defer evaluation');
assert.equal(run('tasteModel().igdb.eval.mae'), 0.1);
assert.equal(run('evaluations'), 2);
run('resetTaste(); tasteModel()');
assert.equal(run('fits'), 3);
assert.equal(run('evaluations'), 2);
run('tasteModel().eval');
assert.equal(run('evaluations'), 3, 'reset discards cached accuracy');
console.log('Prediction fitting, lazy accuracy evaluation, restricted scope and reset passed.');
